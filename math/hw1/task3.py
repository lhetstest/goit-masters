import numpy as np

# 1. Матриця коефіцієнтів A (стовпці - типи дронів: Розвідник, Камікадзе, Вантажний)
A = np.array([
    [4, 4, 6],  # мотори
    [1, 1, 2],  # контролери
    [1, 2, 4]   # акумулятори
])

# Вектор вільних членів b (загальні витрати)
b = np.array([460, 130, 240])

# 2. Перевірка, чи має система розв'язок (визначник відмінний від нуля)
det_A = np.linalg.det(A)
print(f"Визначник матриці A: {det_A:.3f}")

if det_A == 0:
    print("Система не має єдиного розв’язку.")
else:
    # 3. Розв’язок системи
    x = np.linalg.solve(A, b)

    # 4. Перевірка розв’язку (перемноження A*x)
    check = A.dot(x)

    # 5. Вивід результатів
    print("\nКількість зібраних дронів кожного типу:")
    print(f"Розвідник x1: {x[0]:.2f}")
    print(f"Камікадзе x2: {x[1]:.2f}")
    print(f"Вантажний x3: {x[2]:.2f}")

    print("\nПеревірка правильності (A * x):")
    print(check)
    print("\nВектор b:")
    print(b)
